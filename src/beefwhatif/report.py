def fmt(x: float, nd: int = 0, sign: bool = False) -> str:
    """Format a number for LaTeX text: thousands separators, fixed decimals."""
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "--"
    s = f"{x:{'+' if sign else ''},.{nd}f}"
    s = s.replace("-", "\\textminus ") if s.startswith("-") else s
    return s.replace(",", "{,}")


def sig(x: float, n: int = 2, sign: bool = False) -> str:
    """Round to ``n`` significant figures and format."""
    if x == 0 or not np.isfinite(x):
        return fmt(x)
    nd = max(0, n - 1 - int(np.floor(np.log10(abs(x)))))
    return fmt(round(x, nd), nd, sign)


def macro_name(key: str) -> str:
    words = re.split(r"[_\W]+", key)
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
              "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    out = "".join(w[:1].upper() + w[1:] for w in words if w)
    return "".join(digits.get(ch, ch) for ch in out)


class Macros:
    def __init__(self):
        self.items: dict[str, str] = {}
        self.raw: dict[str, float] = {}

    def add(self, key: str, text: str, raw: float | None = None) -> None:
        name = macro_name(key)
        if name in self.items:
            raise KeyError(f"duplicate macro {name}")
        self.items[name] = text
        if raw is not None:
            self.raw[key] = float(raw)

    def num(self, key: str, x: float, nd: int = 0, sign: bool = False) -> None:
        self.add(key, fmt(x, nd, sign), x)

    def sig(self, key: str, x: float, n: int = 2, sign: bool = False) -> None:
        self.add(key, sig(x, n, sign), x)

    def write(self, path) -> None:
        lines = ["% Auto-generated by scripts/run_all.py -- do not edit by hand."]
        lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(self.items.items())]
        path.write_text("\n".join(lines) + "\n")


def q(x, p) -> float:
    return float(np.quantile(np.asarray(x, float), p))


def ci(x, nd=0, scale=1.0) -> str:
    """'median (5th--95th percentile)' string."""
    x = np.asarray(x, float) * scale
    return f"{fmt(q(x, 0.5), nd)} ({fmt(q(x, 0.05), nd)} to {fmt(q(x, 0.95), nd)})"


def tex_escape(s: str) -> str:
    return (str(s).replace("&", "\\&").replace("%", "\\%").replace("_", "\\_")
            .replace("#", "\\#").replace("µ", "\\textmu ").replace("−", "\\textminus "))


def write_tabular(path, header: list[str], rows: list[list[str]], colspec: str,
                  midrules: set[int] | None = None) -> None:
    midrules = midrules or set()
    out = [f"\\begin{{tabular}}{{{colspec}}}", "\\toprule", " & ".join(header) + " \\\\", "\\midrule"]
    for i, r in enumerate(rows):
        if i in midrules:
            out.append("\\midrule")
        out.append(" & ".join(r) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    path.write_text("\n".join(out) + "\n")


