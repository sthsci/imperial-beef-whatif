    M.num("freq_iron_women", abs(fr.loc["iron_mg", "pct_women"]), 1)
    M.num("campus_no_response", lr["substitutes_gross"].median())
    people = P.v("imperial.students") + P.v("imperial.staff_fte")
    M.num("pop_avg_zinc", abs(d["zinc_mg"]) * cc["beef_meals"] / people / 365, 2)
    M.num("campus_people", people)

    # ---- evaluation power calculation
    from scipy.stats import norm
    z = norm.ppf(1 - P.v("evaluation.alpha") / 2) + norm.ppf(P.v("evaluation.power"))
    n = 2 * z ** 2 * P.v("evaluation.zinc_sd_mg") ** 2 / P.v("evaluation.detectable_zinc_mg") ** 2
    M.num("power_n", int(np.ceil(n)))
    M.num("power_sd", P.v("evaluation.zinc_sd_mg"), 1)
    M.num("power_delta", P.v("evaluation.detectable_zinc_mg"), 1)
    return M


