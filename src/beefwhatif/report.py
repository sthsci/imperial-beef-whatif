def grams_text(foods, bk) -> str:
    parts = []
    for f, g in bk.grams.sort_values(ascending=False).items():
        name = str(foods.loc[f, "short"]).split(" (")[0].lower()
        if foods.loc[f, "diet"] == "supplement":
            parts.append(f"{g:.1f} {name}")
        else:
            parts.append(f"{g:.0f}\\,g {name}")
    return ", ".join(parts)


def mass_text(g: float) -> str:
    if not np.isfinite(g):
        return "never"
    return f"{fmt(g)}\\,g" if g < 1000 else f"{fmt(g / 1000, 1)}\\,kg"


